void fn_Heartbeat_Handler(void)
{
	if(!g_vui_HB_Ticker)
	{
		g_vui_HB_Ticker = HB_TIMEOUT; // 1000 ms
		HAL_GPIO_TogglePin(HB_LED_GPIO_Port, HB_LED_Pin);
	}
}
void fn_Process_Rx_Data(void)
{
	if(strstr(g_uc_Final_Rx_Buffer,"LED ON"))
	{
		HAL_GPIO_WritePin(HB_LED_GPIO_Port, HB_LED_Pin, GPIO_PIN_RESET);
		char *ack = "LED is ON\r\n";
		HAL_UART_Transmit(&huart1, (uint8_t *)ack, sizeof(ack), 1000);

	}
	else if(strstr(g_uc_Final_Rx_Buffer,"LED OFF"))
	{
		HAL_GPIO_WritePin(HB_LED_GPIO_Port, HB_LED_Pin, GPIO_PIN_SET);
		char *ack = "LED is OFF\r\n";
		HAL_UART_Transmit(&huart1, (uint8_t *)ack, sizeof(ack), 1000);

	}
	else
	{
		char *ack = "command is wrong. Please choose following commands \r\n 1.LED ON\r\n 2.LED OFF \r\n";
		HAL_UART_Transmit(&huart1, (uint8_t *)ack, sizeof(ack), 1000);
	}

}
